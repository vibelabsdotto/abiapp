// Lucide icon geometry for asset generators. Reads the icon nodes straight
// from lucide-react-native (the version the app ships), so generated assets
// (tab PNGs, Android VectorDrawables) match the icons drawn in the app.

import { readFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "../..",
);
const iconsDir = path.join(
  root,
  "node_modules/lucide-react-native/dist/esm/icons",
);

/** [[tag, attrs], ...] of a Lucide icon by kebab-case name ("chart-pie"). */
export async function lucideNodes(name) {
  const source = await readFile(path.join(iconsDir, `${name}.mjs`), "utf8");
  const literal = source.match(/const __iconData = (\{[\s\S]*?\n\});/)?.[1];
  if (!literal) throw new Error(`lucide: cannot parse ${name}`);
  const data = new Function(`return (${literal});`)();
  return data.node;
}

const attr = (attrs) =>
  Object.entries(attrs)
    .filter(([key]) => key !== "key")
    .map(([key, value]) => `${key}="${value}"`)
    .join(" ");

/** Standalone SVG (24x24 viewBox) in black. */
export async function lucideSvg(name, strokeWidth = 1.75) {
  const nodes = await lucideNodes(name);
  const body = nodes.map(([tag, attrs]) => `<${tag} ${attr(attrs)}/>`).join("");
  return `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="black" stroke-width="${strokeWidth}" stroke-linecap="round" stroke-linejoin="round">${body}</svg>`;
}

const num = (value) => Number(value ?? 0);

/** SVG path data for one Lucide element (VectorDrawable has paths only). */
export function toPathData([tag, a]) {
  switch (tag) {
    case "path":
      return a.d;
    case "circle": {
      const [cx, cy, r] = [num(a.cx), num(a.cy), num(a.r)];
      return `M${cx - r},${cy}a${r},${r} 0 1,0 ${2 * r},0a${r},${r} 0 1,0 ${-2 * r},0`;
    }
    case "ellipse": {
      const [cx, cy, rx, ry] = [num(a.cx), num(a.cy), num(a.rx), num(a.ry)];
      return `M${cx - rx},${cy}a${rx},${ry} 0 1,0 ${2 * rx},0a${rx},${ry} 0 1,0 ${-2 * rx},0`;
    }
    case "line":
      return `M${num(a.x1)},${num(a.y1)}L${num(a.x2)},${num(a.y2)}`;
    case "polyline":
    case "polygon": {
      const pts = String(a.points)
        .trim()
        .split(/[\s,]+/)
        .map(Number);
      let d = "";
      for (let i = 0; i < pts.length; i += 2) {
        d += `${i === 0 ? "M" : "L"}${pts[i]},${pts[i + 1]}`;
      }
      return tag === "polygon" ? `${d}Z` : d;
    }
    case "rect": {
      const [x, y, w, h] = [num(a.x), num(a.y), num(a.width), num(a.height)];
      const r = Math.min(num(a.rx ?? a.ry), w / 2, h / 2);
      if (!r) return `M${x},${y}h${w}v${h}h${-w}Z`;
      return `M${x + r},${y}h${w - 2 * r}a${r},${r} 0 0 1 ${r},${r}v${h - 2 * r}a${r},${r} 0 0 1 ${-r},${r}h${-(w - 2 * r)}a${r},${r} 0 0 1 ${-r},${-r}v${-(h - 2 * r)}a${r},${r} 0 0 1 ${r},${-r}Z`;
    }
    default:
      throw new Error(`lucide: unsupported element <${tag}>`);
  }
}

/** Android VectorDrawable (stroked, black; the menu tints it). */
export async function lucideVectorDrawable(
  name,
  { size = 24, strokeWidth = 1.75 } = {},
) {
  const nodes = await lucideNodes(name);
  const paths = nodes
    .map(
      (node) => `    <path
        android:fillColor="#00000000"
        android:strokeColor="#FF000000"
        android:strokeWidth="${strokeWidth}"
        android:strokeLineCap="round"
        android:strokeLineJoin="round"
        android:pathData="${toPathData(node)}" />`,
    )
    .join("\n");
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Lucide "${name}" (ISC). Generated by scripts/lib/lucide.mjs; do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${size}dp"
    android:height="${size}dp"
    android:viewportWidth="24"
    android:viewportHeight="24">
${paths}
</vector>
`;
}
