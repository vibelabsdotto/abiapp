#!/usr/bin/env node
// Generates the Android menu icons in assets/android-menu-icons/ from Material
// Symbols Outlined (weight 400, 24 px, Apache-2.0). Reads the drawable names
// from src/constants/menuIcons.ts (`menu_<material name>`), downloads each SVG
// and converts its paths into a VectorDrawable. `menu_letter_*` files are
// drawn by hand and skipped. Existing files are kept unless `--force`.
//
//   node scripts/generate-android-menu-icons.mjs [--force]

import { existsSync } from "node:fs";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const mappingFile = path.join(root, "src/constants/menuIcons.ts");
const outDir = path.join(root, "assets/android-menu-icons");
const force = process.argv.includes("--force");

const svgUrl = (name) =>
  `https://fonts.gstatic.com/s/i/short-term/release/materialsymbolsoutlined/${name}/default/24px.svg`;

const toVectorDrawable = (svg, name) => {
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1];
  if (!viewBox) throw new Error(`${name}: no viewBox`);
  const [minX, minY, width, height] = viewBox.split(/[\s,]+/).map(Number);
  const paths = [...svg.matchAll(/<path[^>]*\sd="([^"]+)"/g)].map((m) => m[1]);
  if (paths.length === 0) throw new Error(`${name}: no path`);
  const body = paths
    .map(
      (d) =>
        `        <path\n            android:fillColor="#FF000000"\n            android:pathData="${d}" />`,
    )
    .join("\n");
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Material Symbols Outlined "${name}" (Apache-2.0, Google). Generated by scripts/generate-android-menu-icons.mjs. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="${width}"
    android:viewportHeight="${height}">
    <group
        android:translateX="${-minX}"
        android:translateY="${-minY}">
${body}
    </group>
</vector>
`;
};

const source = await readFile(mappingFile, "utf8");
const drawables = [
  ...new Set([...source.matchAll(/"(menu_[a-z0-9_]+)"/g)].map((m) => m[1])),
].sort();

await mkdir(outDir, { recursive: true });
let written = 0;
const failed = [];
for (const drawable of drawables) {
  const file = path.join(outDir, `${drawable}.xml`);
  if (drawable.startsWith("menu_letter_")) {
    if (!existsSync(file)) failed.push(`${drawable} (hand-drawn, missing)`);
    continue;
  }
  if (existsSync(file) && !force) continue;
  const material = drawable.slice("menu_".length);
  const response = await fetch(svgUrl(material));
  if (!response.ok) {
    failed.push(`${drawable} (HTTP ${response.status})`);
    continue;
  }
  await writeFile(file, toVectorDrawable(await response.text(), material));
  written += 1;
}

console.log(`${drawables.length} drawables, ${written} written`);
if (failed.length > 0) {
  console.error(`missing: ${failed.join(", ")}`);
  process.exitCode = 1;
}
