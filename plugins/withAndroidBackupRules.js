// Android Auto Backup with explicit rules. Android backs the listed data up
// to the user's Google account (about daily, idle, Wi-Fi; end-to-end
// encrypted with a screen lock) and restores it when the app is installed
// again or moved to a new phone. Included:
// - files/SQLite/        all grades (expo-sqlite)
// - files/cloud-backup/  the safety copy before a take-over
// - databases/RKStorage  AsyncStorage (settings, sync metadata)
// Not included: the cache (backup file exports with all grades, always
// excluded by Android), shared_prefs (Firebase measurement state and other
// per-device native state), files/.expo-internal (OTA updates belong to
// the binary) and files/dev-cloud (development stand-in for iCloud).
// fullBackupContent covers Android 11 and lower, dataExtractionRules
// Android 12+ (cloud backup and device-to-device transfer).

const fs = require("fs");
const path = require("path");
const {
  AndroidConfig,
  withAndroidManifest,
  withDangerousMod,
} = require("expo/config-plugins");

const BACKUP_RULES = "abiapp_backup_rules";
const EXTRACTION_RULES = "abiapp_data_extraction_rules";

const INCLUDES = [
  '<include domain="file" path="SQLite/" />',
  '<include domain="file" path="cloud-backup/" />',
  '<include domain="database" path="RKStorage" />',
  '<include domain="database" path="RKStorage-journal" />',
];

const indent = (lines, spaces) =>
  lines.map((line) => `${" ".repeat(spaces)}${line}`).join("\n");

const backupRulesXml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withAndroidBackupRules.js -->
<full-backup-content>
${indent(INCLUDES, 2)}
</full-backup-content>
`;

const extractionRulesXml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by plugins/withAndroidBackupRules.js -->
<data-extraction-rules>
  <cloud-backup>
${indent(INCLUDES, 4)}
  </cloud-backup>
  <device-transfer>
${indent(INCLUDES, 4)}
  </device-transfer>
</data-extraction-rules>
`;

const withRuleFiles = (config) =>
  withDangerousMod(config, [
    "android",
    async (cfg) => {
      const dir = path.join(
        cfg.modRequest.platformProjectRoot,
        "app/src/main/res/xml",
      );
      await fs.promises.mkdir(dir, { recursive: true });
      await fs.promises.writeFile(
        path.join(dir, `${BACKUP_RULES}.xml`),
        backupRulesXml,
      );
      await fs.promises.writeFile(
        path.join(dir, `${EXTRACTION_RULES}.xml`),
        extractionRulesXml,
      );
      return cfg;
    },
  ]);

const withManifestRules = (config) =>
  withAndroidManifest(config, (cfg) => {
    const app = AndroidConfig.Manifest.getMainApplicationOrThrow(
      cfg.modResults,
    );
    app.$["android:allowBackup"] = "true";
    app.$["android:fullBackupContent"] = `@xml/${BACKUP_RULES}`;
    app.$["android:dataExtractionRules"] = `@xml/${EXTRACTION_RULES}`;
    return cfg;
  });

module.exports = (config) => withManifestRules(withRuleFiles(config));
